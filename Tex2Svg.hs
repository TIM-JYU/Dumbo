compose :: [a -> a] -> a -> a
compose = foldr (.) id


-- hack for fixing floats in dvisvgm output - haskell doesn't accept leading dot in fractions
fixFloats :: T.Text -> T.Text
fixFloats s =
  compose
    (map (\x -> T.replace (x <> "=.") (x <> "=0."))
      ["width", "height", "depth"])
    s


invokeDVISVGM
  :: FilePath
  -> DVISVGMPath
  -> FilePath
  -> MathType
  -> MathEnvResult
  -> IO (NonEmpty EqnOut)
invokeDVISVGM curTmp dvisvgm fn mt env = do
  (_, dvi) <- timeoutException 5000000 DVISVGMTimeouted $ readProcessException
    DVISVGMFailed
    curTmp
    (getDVISVGM dvisvgm)
    (getDVISVGMParams fn env mt)
    ""

  case parseOnly
         (many1 parseBlock)
         (fixFloats . LT.toStrict $ LT.pack dvi) of
    Right []       -> throw (UnexpectedError "many1 returned none")
    Right (x : xs) -> pure (x :| xs)
    Left err        -> throw (CouldNotParseDVISVGM dvi err)


