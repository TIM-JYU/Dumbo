-- ============================================================================
-- Legacy SVG output: <img src="data:image/svg+xml;base64,...">
-- ============================================================================

createSVGImg :: EqnOut -> LBS.ByteString -> String -> Html
createSVGImg eb svg eqn =
  img
    ! style
        (toValue $
          "width:" <> tm width <> "; " <>
          "vertical-align:-" <> tm ((/ 1.0) . fromMaybe 0 . depth)
        )
    ! src (toValue $ "data:image/svg+xml;base64," <> encodeSvg svg)
    ! title (toValue eqn)
 where
  encodeSvg =
    LT.unpack . LT.decodeUtf8 . B64.encode

  tm f =
    ($ "em") . showFFloat (Just 5) . toEm . f . metrics $ eb

  toEm =
    estimatePtToEm ""


wrapMath :: MathType -> Html -> Inline
wrapMath mt svg =
  RawInline (Format "html")
    $ LT.toStrict
    $ renderHtml
    $ span
    ! class_ ("mathp " <> (if mt == InlineMath then "inline" else "display"))
    $ svg


-- Add a color attribute matching each fill attribute.
-- This allows currentColor-based strokes to use the same color as the fill,
-- including when the SVG is rendered as an external image.

addColorToFill :: LT.Text -> LT.Text
addColorToFill t =
  case LT.breakOn "fill='" t of
    (before, rest)
      | LT.null rest -> t
      | otherwise ->
          let afterStart = LT.drop 6 rest
              (value, afterValue) = LT.breakOn "'" afterStart
          in before
             <> "fill='"
             <> value
             <> "' color='"
             <> value
             <> "'"
             <> addColorToFill (LT.drop 1 afterValue)


modifySvg :: LBS.ByteString -> LBS.ByteString
modifySvg svg =
  LT.encodeUtf8
    $ addColorToFill
    $ addAttrs
    $ expandUses
    $ stripSvgPreamble (LT.decodeUtf8 svg)
 where
  stripSvgPreamble t =
    let (_, rest) = LT.breakOn "<svg" t
    in if LT.null rest then t else rest

  addAttrs :: LT.Text -> LT.Text
  addAttrs t =
    case LT.breakOn "<svg" t of
      (before, rest)
        | LT.null rest -> t
        | otherwise ->
            let (svgTag, after) = LT.breakOn ">" rest
                svgTag' = removeSizeAttrs svgTag
            in before <> svgTag' <> LT.pack svgAttrs <> after

  removeSizeAttrs :: LT.Text -> LT.Text
  removeSizeAttrs =
    removeAttr "width" . removeAttr "height"

  removeAttr :: LT.Text -> LT.Text -> LT.Text
  removeAttr name t =
    case LT.breakOn (" " <> name <> "='") t of
      (before, rest)
        | LT.null rest -> t
        | otherwise ->
            let afterStart = LT.drop (LT.length name + 3) rest
                (_, afterValue) = LT.breakOn "'" afterStart
            in before <> removeAttr name (LT.drop 1 afterValue)

  attrValue :: LT.Text -> LT.Text -> LT.Text
  attrValue name tag =
    let (_, rest) = LT.breakOn (" " <> name <> "='") tag
    in if LT.null rest
       then ""
       else
         let valueStart = LT.drop (LT.length name + 3) rest
             (value, _) = LT.breakOn "'" valueStart
         in value

  -- Collect path elements from the <defs> section.
  -- Keep each path's ID as the lookup key, but remove the ID from the
  -- copied path because the same path may be inserted more than once.
  extractPaths :: LT.Text -> [(LT.Text, LT.Text)]
  extractPaths t =
    case LT.breakOn "<path " t of
      (_, rest)
        | LT.null rest -> []
        | otherwise ->
            let (tag, afterTag) = LT.breakOn "/>" rest
            in if LT.null afterTag
               then []
               else
                 let fullTag = tag <> "/>"
                     ident = attrValue "id" fullTag
                     pathElement = removeAttr "id" fullTag
                     remaining = LT.drop 2 afterTag
                     found =
                       if LT.null ident
                       then []
                       else [(ident, pathElement)]
                 in found <> extractPaths remaining

  -- Expand <use> elements that reference paths defined in <defs>.
  -- Extract the definitions first, then remove the <defs> section.
  -- Replace each reference with the corresponding path element.
  expandUses :: LT.Text -> LT.Text
  expandUses t =
    case LT.breakOn "<defs>" t of
      (_, rest)
        | LT.null rest -> t
        | otherwise ->
            let (beforeDefs, defsAndAfter) = LT.breakOn "<defs>" t
                defsContent = LT.drop 6 defsAndAfter
                (defs, afterDefs) = LT.breakOn "</defs>" defsContent
                paths = extractPaths defs
                afterDefs' =
                  if LT.null afterDefs
                  then ""
                  else LT.drop 7 afterDefs
                withoutDefs = beforeDefs <> afterDefs'
            in replaceUses paths withoutDefs

  -- Replace each <use> reference with a translated group containing
  -- the referenced path.
  --
  -- The x and y attributes of <use> specify the position at which the
  -- referenced path is placed. Preserve that position with a translate
  -- transform on the enclosing group.
  --
  -- The path geometry itself is not changed. Only the indirect reference
  -- is replaced with the actual path element.
  --
  -- If a reference cannot be resolved, leave the original <use> unchanged.
  replaceUses :: [(LT.Text, LT.Text)] -> LT.Text -> LT.Text
  replaceUses paths t =
    case LT.breakOn "<use " t of
      (before, rest)
        | LT.null rest -> t
        | otherwise ->
            let (tag, afterTag) = LT.breakOn "/>" rest
            in if LT.null afterTag
               then t
               else
                 let fullTag = tag <> "/>"
                     x = attrValue "x" fullTag
                     y = attrValue "y" fullTag
                     href = attrValue "xlink:href" fullTag
                     ident = LT.drop 1 href
                     remaining = LT.drop 2 afterTag
                     replacement =
                       case lookup ident paths of
                         Just pathElement ->
                           "<g transform='translate("
                             <> x <> "," <> y <> ")'>"
                             <> pathElement
                             <> "</g>"
                         Nothing -> fullTag
                 in before <> replacement <> replaceUses paths remaining
				 
-- Create inline SVG markup and add sizing styles.				 
createCSvg :: EqnOut -> LBS.ByteString -> String -> Html
createCSvg eb svg _eqn =
  preEscapedToMarkup
    $ LT.toStrict
    $ insertAttrs
    $ LT.decodeUtf8 (modifySvg svg)
 where
  tm f =
    ($ "em") . showFFloat (Just 5) . toEm . f . metrics $ eb

  svgStyle =
    "width:" <> tm width
      <> ";vertical-align:-"
      <> tm ((/ 1.0) . fromMaybe 0 . depth)
      <> ";"

  insertAttrs t =
    case LT.breakOn "<svg" t of
      (before, afterSvg) ->
        case LT.breakOn ">" afterSvg of
          (openTag, rest) ->
            before
              <> openTag
              <> " style='"
              <> LT.pack svgStyle
              <> "'>"
              <> LT.drop 1 rest

  toEm =
    estimatePtToEm ""


wrapCSvg :: MathType -> String -> Html -> Inline
wrapCSvg mt eqn svg =
  RawInline (Format "html")
    $ LT.toStrict
    $ renderHtml
    $ span
    ! class_ ("mathp " <> (if mt == InlineMath then "inline" else "display"))
    ! title (toValue eqn)
    $ svg


-- ============================================================================
-- New CSVG conversion.
--
-- The LaTeX/DVI/dvisvgm pipeline is shared with the legacy conversion,
-- but the result is emitted as inline SVG instead of a base64-encoded image.
-- ============================================================================
doConvertCSvg
  :: FilePath
  -> DVISVGMPath
  -> LatexPath
  -> String
  -> MathType
  -> String
  -> IO Inline
doConvertCSvg curTmpDir dvisvgm latex preamble mt eqn = do
  let fn        = showDigest . sha1 . LT.encodeUtf8 . LT.pack $ eqn
      env       = parseOnly parseMathEnv (T.pack eqn)
      latexFile = latexTemplate "" preamble mt eqn env

  _ <- timeoutException 5000000 LaTexTimeouted $ readProcessException
    LaTexFailed
    curTmpDir
    (getLatex latex)
    (getLatexParams fn env)
    latexFile

  eb  <- head <$> invokeDVISVGM curTmpDir dvisvgm fn mt env
  svg <- BS.readFile (curTmpDir ++ "/" ++ filename eb)

  return . force . wrapCSvg mt eqn $
    createCSvg eb (LBS.fromStrict svg) eqn


data Tex2SvgRuntime = T2SR
  { readCache  :: Integer -> IO (Maybe Inline)
  , writeCache :: Integer -> Inline -> IO ()
  , tmp        :: FilePath
  , latex      :: LatexPath
  , dvisvgm    :: DVISVGMPath
  }


estimatePtToEm :: T.Text -> (Double -> Double)
estimatePtToEm _preamble =
  (/ 8.3645834169792)


-- ============================================================================
-- Legacy tex2svg.
--
-- DO NOT CHANGE THIS CACHE KEY.
-- Existing cached SVG results must remain accessible.
-- ============================================================================

tex2svg :: Tex2SvgRuntime -> T.Text -> Inline -> IO Inline
tex2svg T2SR {..} preamble (Math mt math) = do
  let cacheKey =
        integerDigest . sha1 . encode $
          (mt, math, preamble)

  cached <- readCache cacheKey

  case cached of
    Nothing ->
      withTempDirectory tmp "tex2svg." $ \curTmpDir -> do
        svg' <- catch
          (do
            result <-
              doConvert
                curTmpDir
                dvisvgm
                latex
                (T.unpack preamble)
                mt
                (T.unpack math)

            writeCache cacheKey result
            return result
          )
          (\e ->
            return
              (renderConversionError
                (T.unpack math)
                (e :: ConversionError)))

        return svg'

    Just s ->
      pure s

tex2svg _ _ il =
  return il


-- ============================================================================
-- New tex2csvg.
--
-- The cache key is prefixed with the byte "c" to prevent collisions with
-- cache keys generated by the legacy tex2svg implementation.
-- ============================================================================

tex2csvg :: Tex2SvgRuntime -> T.Text -> Inline -> IO Inline
tex2csvg T2SR {..} preamble (Math mt math) = do
  let oldKey =
        encode (mt, math, preamble)

      cacheKey =
        integerDigest . sha1 $
          LBS.cons 99 oldKey

  cached <- readCache cacheKey

  case cached of
    Nothing ->
      withTempDirectory tmp "tex2csvg." $ \curTmpDir -> do
        svg' <- catch
          (do
            result <-
              doConvertCSvg
                curTmpDir
                dvisvgm
                latex
                (T.unpack preamble)
                mt
                (T.unpack math)

            writeCache cacheKey result
            return result
          )
          (\e ->
            return
              (renderConversionError
                (T.unpack math)
                (e :: ConversionError)))

        return svg'

    Just s ->
      pure s

tex2csvg _ _ il =
  return il