
-- ============================================================================
-- Tex2Svg.hs
--
-- Purpose:
-- Convert LaTeX mathematical expressions into SVG graphics for use in TIM.
--
-- The module supports two output formats:
--
--   1. Legacy SVG output (`tex2svg`):
--      The generated SVG is embedded in an HTML <img> element as a
--      Base64-encoded data URL.
--
--   2. Inline SVG output (`tex2csvg`):
--      The generated SVG is embedded directly in the HTML document.
--      This allows CSS styles, including currentColor, to work in the
--      surrounding document.
--
-- Conversion pipeline:
-- LaTeX source -> LaTeX compiler -> DVI -> dvisvgm -> SVG
--
-- The module also handles conversion errors, caches generated results,
-- adjusts SVG attributes and styles, and expands certain SVG <use>
-- references into their corresponding path elements.
--
-- The legacy and inline SVG implementations share conversion infrastructure,
-- but their output handling differs. Changes to the shared code must preserve
-- the behavior of both output formats.
--
-- IMPORTANT:
-- Do not change the existing cache key generated by tex2svg. The tex2csvg
-- cache key uses a separate prefix to avoid collisions with legacy entries.
-- ============================================================================

