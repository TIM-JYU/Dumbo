  LaTex <$> (fromMaybe (throw NoLatex) <$> findExecutable "xelatex")


mkDVISVGM :: FilePath -> IO DVISVGMPath
mkDVISVGM fp = do
  e <- doesFileExist fp
  unless e (throw NoDVISVGM)
  pure (DVISVGM fp)


